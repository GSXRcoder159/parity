const SHA = "2bab97685e29abae0c241680c2257153e259e50f";
const BASE = `https://raw.githubusercontent.com/stripe/openapi/${SHA}`;
const SPEC_URL = `${BASE}/latest/openapi.spec3.json`;
const OUT = join(import.meta.dirname, "../src/twin/spec");

