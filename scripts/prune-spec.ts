async function download(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v === null || typeof v !== "object") return v;
  const o = v as Record<string, unknown>;
  return Object.fromEntries(Object.keys(o).sort().map((k) => [k, sortKeys(o[k])]));
}

const tmpDir = mkdtempSync(join(tmpdir(), "parity-spec-"));
const tmp = join(tmpDir, "openapi.spec3.json");
writeFileSync(tmp, await download(SPEC_URL));
const spec = JSON.parse(readFileSync(tmp, "utf8"));
rmSync(tmpDir, { recursive: true });
const schemas: Record<string, unknown> = spec.components.schemas;

const paths: Record<string, Record<string, unknown>> = {};
for (const [method, path] of OPERATIONS) {
  const op = spec.paths[path]?.[method];
  if (!op) throw new Error(`spec has no ${method.toUpperCase()} ${path}`);
  (paths[path] ??= {})[method] = op;
}

const kept: Record<string, unknown> = {};
const walk = (v: unknown): void => {
  if (Array.isArray(v)) return v.forEach(walk);
  if (v === null || typeof v !== "object") return;
  for (const [k, x] of Object.entries(v)) {
    if (k !== "$ref") { walk(x); continue; }
    const name = String(x).replace("#/components/schemas/", "");
    if (!(name in schemas)) throw new Error(`unresolvable $ref ${String(x)}`);
    if (!(name in kept)) { kept[name] = schemas[name]; walk(schemas[name]); }
  }
};
walk(paths);
// Extra roots: schemas no in-scope operation references but the twin still builds (legacy plan.* event payloads).
const EXTRA_SCHEMAS = ["plan"];
walk(EXTRA_SCHEMAS.map((n) => ({ $ref: `#/components/schemas/${n}` })));

const pruned = { ...spec, paths, components: { ...spec.components, schemas: kept } };
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "openapi.pruned.json"), JSON.stringify(sortKeys(pruned), null, 2) + "\n");
writeFileSync(join(OUT, "LICENSE-stripe-openapi"), await download(`${BASE}/LICENSE`));
writeFileSync(join(OUT, "README.md"), `# Pruned OpenAPI spec

\`openapi.pruned.json\` is generated by \`scripts/prune-spec.ts\` from the OpenAPI description of the Stripe API published at https://github.com/stripe/openapi under the MIT license (copied verbatim to \`LICENSE-stripe-openapi\`).

- Source: ${SPEC_URL}
- Commit: ${SHA}
- API version: ${spec.info.version}

It keeps the twin's ${OPERATIONS.length} in-scope operations and the ${Object.keys(kept).length} component schemas reachable from them or from the extra roots ${EXTRA_SCHEMAS.join(", ")} (legacy \`plan.*\` event payloads). Everything kept is unmodified except that object keys are sorted.

Regenerate this directory and the object templates in \`src/twin/shapes/\` with \`node scripts/prune-spec.ts && node scripts/gen-shapes.ts\`.
`);
console.log(`kept ${OPERATIONS.length} operations, ${Object.keys(kept).length} schemas`);
